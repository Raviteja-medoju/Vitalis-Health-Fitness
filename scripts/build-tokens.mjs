#!/usr/bin/env node
/**
 * Build typed TypeScript tokens from the W3C DTCG token file.
 *   node scripts/build-tokens.mjs          -> writes src/design-system/tokens/generated.ts
 *   node scripts/build-tokens.mjs --check  -> exits 1 if generated.ts is stale (CI gate)
 *
 * Governance: tokens.json is the single source of truth shared with Figma Variables.
 * Never hand-edit generated.ts.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const srcPath = path.join(root, 'src/design-system/tokens/tokens.json');
const outPath = path.join(root, 'src/design-system/tokens/generated.ts');
const check = process.argv.includes('--check');

const tokens = JSON.parse(fs.readFileSync(srcPath, 'utf8'));

function get(obj, dotted) {
  return dotted.split('.').reduce((acc, k) => (acc == null ? undefined : acc[k]), obj);
}

function resolveRef(value, seen = new Set()) {
  if (typeof value !== 'string') return value;
  const m = value.match(/^\{(.+)\}$/);
  if (!m) return value;
  if (seen.has(m[1])) throw new Error(`Circular token reference: ${m[1]}`);
  seen.add(m[1]);
  const target = get(tokens, m[1]);
  if (!target || !('$value' in target)) throw new Error(`Unresolved token reference: ${value}`);
  return resolveRef(target.$value, seen);
}

function num(v) {
  if (typeof v === 'number') return v;
  const m = String(v).match(/^(-?\d+(?:\.\d+)?)(px|ms)?$/);
  if (!m) throw new Error(`Cannot parse dimension/duration: ${v}`);
  return Number(m[1]);
}

function walk(node, visit, trail = []) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    if (v && typeof v === 'object' && '$value' in v) visit(trail.concat(k), v);
    else if (v && typeof v === 'object') walk(v, visit, trail.concat(k));
  }
}

// ---- primitives ----
const prim = {};
walk(tokens.primitive, (trail, tok) => {
  const [group, ...rest] = trail;
  const key = rest.join('.');
  prim[group] ??= {};
  const raw = resolveRef(tok.$value);
  let val;
  switch (tok.$type) {
    case 'color':
      val = raw;
      break;
    case 'dimension':
    case 'duration':
      val = num(raw);
      break;
    case 'number':
    case 'fontWeight':
      val = Number(raw);
      break;
    default:
      val = raw;
  }
  prim[group][key] = val;
});

// ---- semantic colors per mode ----
const modes = { light: {}, dark: {} };
walk(tokens.semantic.color, (trail, tok) => {
  const [group, name] = trail;
  for (const mode of Object.keys(modes)) {
    const ref = tok.$extensions?.modes?.[mode] ?? tok.$value;
    modes[mode][group] ??= {};
    modes[mode][group][name] = resolveRef(ref);
  }
});

// ---- component tokens ----
const component = {};
walk(tokens.component, (trail, tok) => {
  const [group, name] = trail;
  component[group] ??= {};
  component[group][name] = num(resolveRef(tok.$value));
});

const header = `/* eslint-disable */
// AUTO-GENERATED by scripts/build-tokens.mjs from tokens.json. DO NOT EDIT.
// Run "npm run tokens:build" after changing tokens.json.
`;

const body = `
export const primitive = ${JSON.stringify(prim, null, 2)} as const;

export const semanticColors = ${JSON.stringify(modes, null, 2)} as const;

export const componentTokens = ${JSON.stringify(component, null, 2)} as const;

export type ColorScheme = keyof typeof semanticColors;
type Widen<T> = { [G in keyof T]: { [K in keyof T[G]]: string } };
export type SemanticColors = Widen<(typeof semanticColors)['light']>;
`;

const out = header + body;

if (check) {
  const existing = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
  if (existing.replace(/\r\n/g, '\n') !== out.replace(/\r\n/g, '\n')) {
    console.error(
      'FAIL tokens: generated.ts is out of date. Run "npm run tokens:build" and commit.',
    );
    process.exit(1);
  }
  console.log('OK tokens: generated.ts is up to date');
} else {
  fs.writeFileSync(outPath, out);
  console.log(`OK tokens: wrote ${path.relative(root, outPath)}`);
}
